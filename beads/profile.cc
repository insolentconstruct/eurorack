static uint32_t Read32(const volatile uint8_t* p) {
  return uint32_t(p[0]) | uint32_t(p[1]) << 8 |
      uint32_t(p[2]) << 16 | uint32_t(p[3]) << 24;
}

/* static */
uint32_t Profile::Crc32(const volatile uint8_t* data, size_t size) {
  uint32_t crc = 0xffffffff;
  while (size--) {
    crc ^= *data++;
    for (int i = 0; i < 8; ++i) {
      crc = (crc >> 1) ^ ((crc & 1) ? 0xedb88320 : 0);
    }
  }
  return ~crc;
}

static float ReadFloat(const volatile uint8_t* p) {
  const uint32_t bits = Read32(p);
  float value;
  memcpy(&value, &bits, sizeof(value));
  return value;
}

static bool ScaleFloat(const volatile uint8_t* p) {
  const uint32_t bits = Read32(p);
  const uint32_t exponent = bits & 0x7f800000;
  return !bits || (exponent && exponent != 0x7f800000);
}

static bool ScaleName(const volatile uint8_t* p) {
  size_t i = 0;
  while (i < kScaleNameSize && p[i]) {
    const uint8_t first = p[i++];
    uint32_t code = first;
    size_t remaining = 0;
    uint32_t minimum = 0;
    if (first >= 0xc2 && first <= 0xdf) {
      code = first & 0x1f;
      remaining = 1;
      minimum = 0x80;
    } else if (first >= 0xe0 && first <= 0xef) {
      code = first & 0x0f;
      remaining = 2;
      minimum = 0x800;
    } else if (first >= 0xf0 && first <= 0xf4) {
      code = first & 0x07;
      remaining = 3;
      minimum = 0x10000;
    } else if (first >= 0x80) {
      return false;
    }
    while (remaining--) {
      if (i >= kScaleNameSize || (p[i] & 0xc0) != 0x80) {
        return false;
      }
      code = (code << 6) | (p[i++] & 0x3f);
    }
    if (code < minimum || code > 0x10ffff ||
        (code >= 0xd800 && code <= 0xdfff) ||
        code < 0x20 || (code >= 0x7f && code <= 0x9f)) {
      return false;
    }
  }
  if (!i || i == kScaleNameSize) {
    return false;
  }
  while (i < kScaleNameSize) {
    if (p[i++]) {
      return false;
    }
  }
  return true;
}

