# Write beads/blob/plaits_catalog.cc: the release number, the approved blob
# digests and the default layout (blob_sections.py's JSON), which a
# development build uses without a profile directory.
#
#   blob_catalog.py OUT.cc RELEASE REGION.json BLOB.bin...

import hashlib
import json
import sys

KINDS = {'WAVE': 'kPlaitsSectionWave', 'TERR': 'kPlaitsSectionTerrain',
         'PLTS': 'kPlaitsSectionPlaits', 'RNGS': 'kPlaitsSectionRings'}


def digest(hex_text, indent):
  data = bytes.fromhex(hex_text)
  rows = []
  for i in range(0, 32, 8):
    rows.append(indent + ', '.join('0x%02x' % b for b in data[i:i + 8]))
  return ',\n'.join(rows)


def main(argv):
  out, release, layout_path = argv[1], int(argv[2], 0), argv[3]
  layout = json.load(open(layout_path))
  if layout['release'] != release:
    raise ValueError('the region was written for another release')
  blobs = sorted(set(hashlib.sha256(open(p, 'rb').read()).hexdigest()
                     for p in argv[4:]))
  # The licence, from the hand-written header.
  licence = ''.join(open('beads/blob/plaits_catalog.h').readlines()[:24])
  text = [licence + '// ' + '-' * 77, '//',
          '// Generated by beads/build/tools/blob_catalog.py; do not edit.', '',
          '#include "beads/blob/plaits_catalog.h"', '',
          'namespace beads {', '',
          'const uint32_t kPlaitsBlobRelease = %d;' % release, '',
          'const uint8_t kPlaitsApprovedBlobs[][kPlaitsBlobDigestSize] = {']
  text.append(',\n'.join('  {\n%s\n  }' % digest(d, '    ') for d in blobs))
  text += ['};', '',
           'const size_t kNumPlaitsApprovedBlobs = %d;' % len(blobs), '',
           'const PlaitsDefaultSection kPlaitsDefaultLayout[] = {']
  sections = []
  for s in layout['sections']:
    sections.append('  {\n    %s, %d, %d,\n    {\n%s\n    }\n  }' % (
        KINDS[s['kind']], s['offset'], s['size'],
        digest(s['sha256'], '      ')))
  text.append(',\n'.join(sections))
  text += ['};', '',
           'const size_t kNumPlaitsDefaultSections = %d;' % len(sections), '',
           '}  // namespace beads', '']
  open(out, 'w').write('\n'.join(text))
  return 0


if __name__ == '__main__':
  sys.exit(main(sys.argv))
