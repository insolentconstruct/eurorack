"""Generate options guides from options_tables TSV; Python 3 stdlib only."""
import argparse
import csv
import io
import math
from pathlib import Path
import sys
import textwrap
from html import escape

KNOBS = ("FEEDBACK", "DRY/WET", "REVERB")
COLOURS = {"green": "#247443", "yellow": "#a87900", "red": "#bd3030",
           "meter": "#777", "unchanged": "#777"}
STEPS = [
    "Enter: hold ASSIGN alone 3 s with mix knobs still, then release.",
    "Next page: tap ASSIGN. Pages cycle 1 → 2 → 3 → 1.",
    "Leave: hold ASSIGN 3 s or press another button (SEED exception below).",
    "Save: rest the knob 1 s; the page LED flashes briefly (100 ms).",
    "Pending edits save after leaving too. Wait 1 s before powering off.",
    "Move a knob more than 10% to begin editing. Reserved knobs do nothing.",
    "MEDIA shows the first setting on entry, then the last qualified knob moved.",
    "No idle exit or cancel. Reopening remembers the page until power-off.",
]
NOTES = [
    "Arc numbers match values below (CCW to CW); edges have a 3% dead band.",
    "Pitch: Off / Chromatic / Scale in thirds. On Scale, tap SEED to cycle",
    "the eight scales below in order. Holds do not cycle; taps do not play grains.",
    "Width: Stock below 10%; leave above 13%, return below 7%.",
    "Enabled width runs from zero spread at 13% to full spread at 100%.",
    "Zero preserves stereo position (mono centred); changes affect new grains.",
    "All three mix LEDs pulse on entry; one marks the page thereafter.",
    "The page LED flashes on entry, exit and after saving changed values.",
]
LEGEND = [
    "MEDIA: solid ring = steady; dashed ring = slow ≈1 Hz; dotted ring = fast ≈4 Hz.",
    "Two dots = two yellow pulses then a pause (2.048 s group). Colour is also named.",
    "Width meter: slow green → yellow → red for zero → full enabled spread.",
    "First value = steady green. Reserved = MEDIA unchanged. Page LED ≠ MEDIA.",
]


def read_tsv(data):
    rows = list(csv.DictReader(io.StringIO(data), delimiter="\t"))
    assert rows and list(rows[0]) == ["page", "LED", "knob", "setting", "value", "colour", "pulse"]
    pages = {}
    for row in rows:
        pages.setdefault(row["page"], {}).setdefault(row["knob"], []).append(row)
    assert list(pages) == ["1", "2", "3"]
    assert all(set(page) == set(KNOBS) for page in pages.values())
    return rows, pages


def zones(rows):
    setting = rows[0]["setting"]
    values = [r["value"] for r in rows]
    if setting == "Reserved":
        return [(0, 1, "Reserved")]
    if setting == "Pitch scale":
        values = values[:2] + ["Scale: tap SEED"]
    if setting == "Stereo width":
        return [(0, .1, values[0]), (.1, 1, "Width 0 → full")]
    return [(i / len(values), (i + 1) / len(values), value)
            for i, value in enumerate(values)]


def indication(row):
    if row["colour"] == "meter":
        return "green → yellow → red meter; " + row["pulse"]
    if row["colour"] == "unchanged":
        return "unchanged"
    return row["colour"] + "; " + row["pulse"]


def markdown(rows, pages):
    out = ["<!-- Author: Insolent Construct. Generated by options_guide.py. -->",
           "# Options page", "", "**TL;DR:** Hold ASSIGN for 3 seconds and release. Tap to change page;",
           "move a mix knob to edit, then rest it for 1 second to save.", "",
           "[Printable guide](options-guide.svg) · [Phone guide](options-guide-mobile.svg)",
           "", "![Options control guide](options-guide.svg)", "", "## Steps", ""]
    out += [f"{i}. {step}" for i, step in enumerate(STEPS, 1)]
    out += ["", "## Reading the controls", ""] + NOTES + ["", "## MEDIA LED legend", ""] + LEGEND
    for page, knobs in pages.items():
        led = next(iter(knobs.values()))[0]["LED"]
        out += ["", f"## Page {page} — {led} LED pulses", "",
                "| Knob | Setting | Zone (CCW → CW) |", "|---|---|---|"]
        for knob, values in knobs.items():
            zs = "; ".join(f"{a*100:.3g}–{b*100:.3g}%: {v}" for a,b,v in zones(values))
            out.append(f"| {knob} | {values[0]['setting']} | {zs} |")
        out += ["", "| Page | Knob | Value | MEDIA LED |", "|---|---|---|---|"]
        for values in knobs.values():
            for row in values:
                out.append(f"| {page} | {row['knob']} | {row['value']} | {indication(row)} |")
    out += ["", "## What changes", "",
            "Pitch snaps new grains to the selected scale; playing grains keep their pitch.",
            "The continuous synth oscillator and delay pitch keep their usual behaviour.",
            "Pelog and the raags are microtonal. The root is unity (0 semitones).", "",
            "Width sets random pan spread for new grains. When enabled, normal ASSIGN",
            "cycling adds WIDTH after the three mix destinations; all three LEDs pulse.",
            "ASSIGN CV adds to the saved width and clamps at zero and full spread.", "",
            "Reverb selects Stock or Clouds-style. Switching briefly fades and clears the tail.",
            "Delay Auto switches at SIZE fully clockwise; Never stays granular.",
            "Wide detent adds an unfiltered 40–60% zone to SIZE attenurandomizer plus",
            "SIZE CV and removes resonant boost; synth mode is unaffected.", "",
            "Self-play Automatic starts as usual. On request requires both inputs unpatched",
            "and FREEZE off: hold MEDIA 1.5 s to start or stop. Patching an input stops it",
            "once FREEZE is off. Limiter Off allows loud peaks to hard-clip.", ""]
    return "\n".join(out)


class Drawing:
    def __init__(self):
        self.items = []

    def text(self, x, y, value, size=13, weight="normal"):
        self.items.append(f'<text x="{x}" y="{y}" font-size="{size}" font-weight="{weight}">{escape(value)}</text>')

    def circle(self, x, y, r, colour="white", pattern=""):
        dash = ' stroke-dasharray="6 4"' if pattern.startswith("slow") else ' stroke-dasharray="1 3"' if pattern.startswith("fast") else ""
        self.items.append(f'<circle cx="{x}" cy="{y}" r="{r}" fill="{colour}" stroke="#222" stroke-width="1.5"{dash}/>')
        if pattern.startswith("2 "):
            self.circle(x-3,y,1,"#222")
            self.circle(x+3,y,1,"#222")

    def arc(self, x, y, a, b):
        def point(t):
            angle = math.radians(135 + 270*t)
            return x+37*math.cos(angle), y+37*math.sin(angle)
        x1,y1=point(a+.012); x2,y2=point(b-.012)
        self.items.append(f'<path d="M {x1:.3f} {y1:.3f} A 37 37 0 {int(b-a>.6667)} 1 {x2:.3f} {y2:.3f}" fill="none" stroke="#222" stroke-width="3"/>')

    def card(self, x, y, width, rows):
        self.text(x, y, rows[0]["knob"], 16, "bold")
        self.text(x, y+20, rows[0]["setting"], 14)
        cx,cy=x+width/2,y+79
        self.circle(cx, cy, 22)
        self.items.append(f'<path d="M {cx} {cy} v -16" stroke="#222" stroke-width="2"/>')
        zs=zones(rows)
        for i,(a,b,value) in enumerate(zs):
            self.arc(cx,cy,a,b)
            angle=math.radians(135+270*((a+b)/2))
            self.text(round(cx+50*math.cos(angle)-4,2),round(cy+50*math.sin(angle)+4,2),str(i+1),12,"bold")
            # Numbered labels keep long names away from the arcs.
            if rows[0]["setting"] == "Pitch scale":
                self.text(x,y+139+i*16,f"{i+1}. {value}",12)
        base=y+139+(len(zs)*16+8 if rows[0]["setting"] == "Pitch scale" else 0)
        for i,row in enumerate(rows):
            yy=base+i*17
            self.circle(x+5,yy-4,5,COLOURS[row["colour"]],row["pulse"])
            value=row["value"]
            short = {"slow (0.98 Hz)":"slow", "fast (3.91 Hz)":"fast", "2 yellow pulses / 2.048 s":"two pulses"}.get(row["pulse"],row["pulse"])
            colour="G→Y→R meter" if row["colour"]=="meter" else row["colour"]
            self.text(x+17,yy,f"{value}: {colour}, {short}" if rows[0]["setting"] == "Pitch scale" else f"{i+1}. {value}: {colour}, {short}",13)
        return max(195,base-y+len(rows)*17+12)


def svg(pages, mobile=False):
    d=Drawing()
    width=390 if mobile else 1060
    margin=20 if mobile else 35
    d.text(margin,35,"OPTIONS / CONTROL GUIDE",22,"bold")
    d.text(margin,56,"ASSIGN • SEED • FREEZE • MEDIA • MIX",12)
    # Original schematic of only the controls used, not a panel reproduction.
    for i,name in enumerate(("ASSIGN","SEED","FREEZE","MEDIA LED")):
        x=margin+35+i*85
        d.circle(x,86,10)
        d.text(x-26,110,name,11)
    y=145 if mobile else 125
    start=y
    column_bottoms=[]
    for i,line in enumerate(STEPS):
        if not mobile and i == 4:
            column_bottoms.append(y)
            y=start
        x=margin+(500 if not mobile and i >= 4 else 0)
        for part in textwrap.wrap(line, 49 if mobile else 63):
            d.text(x,y,part,13); y+=18
    y=max([y]+column_bottoms)
    y+=8
    for line in LEGEND:
        for part in textwrap.wrap(line,49 if mobile else 125):
            d.text(margin,y,part,12); y+=17
    for i,(label,pattern) in enumerate((("steady","steady"),("slow","slow"),("fast","fast"),("two pulses","2 "))):
        x=margin+10+i*88
        d.circle(x,y+5,7,"white",pattern); d.text(x+12,y+9,label,10)
    y+=40
    for page,knobs in pages.items():
        led=next(iter(knobs.values()))[0]["LED"]
        d.text(margin,y,f"PAGE {page} / {led} LED PULSES",17,"bold")
        y+=30
        if mobile:
            for knob in KNOBS:
                d.circle(width-40,y-5,6,"#222" if knob==led else "white","slow" if knob==led else "")
                y+=d.card(margin,y,width-2*margin,knobs[knob])+12
        else:
            heights=[]
            for i,knob in enumerate(KNOBS):
                x=margin+i*330
                d.circle(x+290,y-5,6,"#222" if knob==led else "white","slow" if knob==led else "")
                heights.append(d.card(x,y,315,knobs[knob]))
            y+=max(heights)+15
    start=y
    column_bottoms=[]
    for i,line in enumerate(NOTES):
        if not mobile and i == 4:
            column_bottoms.append(y)
            y=start
        x=margin+(500 if not mobile and i >= 4 else 0)
        for part in textwrap.wrap(line,49 if mobile else 72):
            d.text(x,y,part,12); y+=15
    y=max([y]+column_bottoms)
    d.text(margin,y+12,"Author: Insolent Construct • Generated control schematic",10)
    height=y+35
    physical=f'width="190mm" height="{190*height/width:.2f}mm"' if not mobile else f'width="390" height="{height}"'
    assert mobile or height/width < 254/190, f"Exceeds Letter-safe print area: {height}x{width}"
    return f'<svg xmlns="http://www.w3.org/2000/svg" {physical} viewBox="0 0 {width} {height}" role="img" aria-labelledby="title desc">\n<title id="title">Options page control guide</title>\n<desc id="desc">Three pages of mix knob settings with MEDIA colour and blink indications. Full text version in OPTIONS.md.</desc>\n<metadata>Author: Insolent Construct</metadata>\n<rect width="100%" height="100%" fill="white"/>\n<g font-family="sans-serif" fill="#222">\n'+"\n".join(d.items)+"\n</g>\n</svg>\n"


def generate(data):
    rows,pages=read_tsv(data)
    return {"OPTIONS.md":markdown(rows,pages), "options-guide.svg":svg(pages),
            "options-guide-mobile.svg":svg(pages,True)}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=Path(__file__).resolve().parents[1])
    args=parser.parse_args()
    args.output_dir.mkdir(parents=True,exist_ok=True)
    for name,data in generate(sys.stdin.read()).items():
        (args.output_dir/name).write_bytes(data.encode("utf-8"))


if __name__ == "__main__":
    main()
